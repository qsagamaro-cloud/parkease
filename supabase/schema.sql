-- PARKEASE: Supabase schema + required starter rows
-- Run this once in Supabase > SQL Editor (safe to re-run).

create table if not exists public.slots (
  slot_number int primary key,
  status text not null default 'available' check (status in ('available','occupied')),
  distance_cm int,
  last_update bigint
);

create table if not exists public.logs (
  id bigint generated by default as identity primary key,
  "timestamp" bigint not null,
  slot_number int not null,
  status text not null,
  distance_cm int,
  plate_number text
);

create table if not exists public.api_keys (
  id bigint generated by default as identity primary key,
  key_value text unique not null,
  device_name text
);

-- Lock the tables: only your server (using the service_role key) can read/write them.
alter table public.slots enable row level security;
alter table public.logs enable row level security;
alter table public.api_keys enable row level security;

create index if not exists logs_id_desc on public.logs (id desc);

